#include "AdvancedPython.h"

namespace iiGraphicAdjust::python {
// These value bindings reproduce the native geometry settings. Nested arrays
// are copied across the language boundary; ownership remains with Python.
void bindGeometry(py::module_& module) {
    using namespace objects;
    py::enum_<MeshInterpolation>(module,"MeshInterpolation")
        .value("NEAREST",MeshInterpolation::Nearest).value("BILINEAR",MeshInterpolation::Bilinear)
        .value("BICUBIC",MeshInterpolation::Bicubic);
    py::enum_<PuppetMode>(module,"PuppetMode")
        .value("RIGID",PuppetMode::Rigid).value("NORMAL",PuppetMode::Normal).value("DISTORT",PuppetMode::Distort);
    py::enum_<PuppetDensity>(module,"PuppetDensity")
        .value("FEWER",PuppetDensity::Fewer).value("NORMAL",PuppetDensity::Normal).value("MORE",PuppetDensity::More);
    py::class_<PuppetPin>(module,"PuppetPin").def(py::init<>())
        .def_readwrite("source",&PuppetPin::source).def_readwrite("destination",&PuppetPin::destination)
        .def_readwrite("rotation",&PuppetPin::rotation).def_readwrite("depth",&PuppetPin::depth);
    py::class_<PuppetWarpOptions>(module,"PuppetWarpOptions").def(py::init<>())
        .def_readwrite("pins",&PuppetWarpOptions::pins).def_readwrite("mode",&PuppetWarpOptions::mode)
        .def_readwrite("density",&PuppetWarpOptions::density).def_readwrite("expansion",&PuppetWarpOptions::expansion)
        .def_readwrite("iterations",&PuppetWarpOptions::iterations)
        .def_readwrite("solver_iterations",&PuppetWarpOptions::solverIterations)
        .def_readwrite("interpolation",&PuppetWarpOptions::interpolation);
    py::class_<PerspectivePlane>(module,"PerspectivePlane").def(py::init<>())
        .def_readwrite("source",&PerspectivePlane::source).def_readwrite("destination",&PerspectivePlane::destination);
    py::enum_<PerspectiveStraighten>(module,"PerspectiveStraighten")
        .value("NONE",PerspectiveStraighten::None).value("HORIZONTAL",PerspectiveStraighten::Horizontal)
        .value("VERTICAL",PerspectiveStraighten::Vertical).value("AUTO",PerspectiveStraighten::Auto);
    py::class_<PerspectiveWarpOptions>(module,"PerspectiveWarpOptions").def(py::init<>())
        .def_readwrite("planes",&PerspectiveWarpOptions::planes).def_readwrite("straighten",&PerspectiveWarpOptions::straighten)
        .def_readwrite("cell",&PerspectiveWarpOptions::cell).def_readwrite("interpolation",&PerspectiveWarpOptions::interpolation);
    py::enum_<WideAngleModel>(module,"WideAngleModel")
        .value("AUTO",WideAngleModel::Auto).value("FISHEYE",WideAngleModel::Fisheye)
        .value("PERSPECTIVE",WideAngleModel::Perspective).value("FULL_SPHERICAL",WideAngleModel::FullSpherical);
    py::enum_<WideAngleOrientation>(module,"WideAngleOrientation")
        .value("FREE",WideAngleOrientation::Free).value("HORIZONTAL",WideAngleOrientation::Horizontal)
        .value("VERTICAL",WideAngleOrientation::Vertical);
    py::class_<WideAngleConstraint>(module,"WideAngleConstraint").def(py::init<>())
        .def_readwrite("a",&WideAngleConstraint::a).def_readwrite("b",&WideAngleConstraint::b)
        .def_readwrite("orientation",&WideAngleConstraint::orientation);
    py::class_<AdaptiveWideAngleOptions>(module,"AdaptiveWideAngleOptions").def(py::init<>())
        .def_readwrite("model",&AdaptiveWideAngleOptions::model).def_readwrite("focal_length",&AdaptiveWideAngleOptions::focalLength)
        .def_readwrite("crop_factor",&AdaptiveWideAngleOptions::cropFactor).def_readwrite("scale",&AdaptiveWideAngleOptions::scale)
        .def_readwrite("constraints",&AdaptiveWideAngleOptions::constraints).def_readwrite("mesh_cells",&AdaptiveWideAngleOptions::meshCells)
        .def_readwrite("solver_iterations",&AdaptiveWideAngleOptions::solverIterations)
        .def_readwrite("interpolation",&AdaptiveWideAngleOptions::interpolation);
    py::enum_<LensFilterEdge>(module,"LensFilterEdge")
        .value("EXTENSION",LensFilterEdge::Extension).value("TRANSPARENCY",LensFilterEdge::Transparency)
        .value("COLOR",LensFilterEdge::Color);
    py::class_<LensFilterProfile>(module,"LensFilterProfile").def(py::init<>())
        .def_readwrite("k1",&LensFilterProfile::k1).def_readwrite("k2",&LensFilterProfile::k2)
        .def_readwrite("p1",&LensFilterProfile::p1).def_readwrite("p2",&LensFilterProfile::p2)
        .def_readwrite("vignette",&LensFilterProfile::vignette).def_readwrite("ca_red",&LensFilterProfile::caRed)
        .def_readwrite("ca_blue",&LensFilterProfile::caBlue);
    py::class_<LensCorrectionOptions>(module,"LensCorrectionOptions").def(py::init<>())
        .def_readwrite("profile",&LensCorrectionOptions::profile)
        .def_readwrite("correct_distortion",&LensCorrectionOptions::correctDistortion)
        .def_readwrite("correct_vignette",&LensCorrectionOptions::correctVignette)
        .def_readwrite("correct_ca",&LensCorrectionOptions::correctCa)
        .def_readwrite("distortion",&LensCorrectionOptions::distortion)
        .def_readwrite("red_cyan",&LensCorrectionOptions::redCyan).def_readwrite("blue_yellow",&LensCorrectionOptions::blueYellow)
        .def_readwrite("vignette_amount",&LensCorrectionOptions::vignetteAmount)
        .def_readwrite("vignette_midpoint",&LensCorrectionOptions::vignetteMidpoint)
        .def_readwrite("vertical",&LensCorrectionOptions::vertical).def_readwrite("horizontal",&LensCorrectionOptions::horizontal)
        .def_readwrite("angle",&LensCorrectionOptions::angle).def_readwrite("scale",&LensCorrectionOptions::scale)
        .def_readwrite("edge",&LensCorrectionOptions::edge).def_readwrite("edge_color",&LensCorrectionOptions::edgeColor);
    py::enum_<LiquifyTool>(module,"LiquifyTool")
        .value("FORWARD_WARP",LiquifyTool::ForwardWarp).value("RECONSTRUCT",LiquifyTool::Reconstruct)
        .value("SMOOTH",LiquifyTool::Smooth).value("TWIRL_CLOCKWISE",LiquifyTool::TwirlClockwise)
        .value("TWIRL_COUNTERCLOCKWISE",LiquifyTool::TwirlCounterclockwise)
        .value("PUCKER",LiquifyTool::Pucker).value("BLOAT",LiquifyTool::Bloat).value("PUSH_LEFT",LiquifyTool::PushLeft)
        .value("FREEZE",LiquifyTool::Freeze).value("THAW",LiquifyTool::Thaw).value("LASSO_MASK",LiquifyTool::LassoMask)
        .value("RECONSTRUCT_ALL",LiquifyTool::ReconstructAll).value("FREEZE_ALL",LiquifyTool::FreezeAll)
        .value("THAW_ALL",LiquifyTool::ThawAll).value("INVERT_FREEZE",LiquifyTool::InvertFreeze);
    py::class_<LiquifyPoint>(module,"LiquifyPoint").def(py::init<>())
        .def_readwrite("position",&LiquifyPoint::position).def_readwrite("pressure",&LiquifyPoint::pressure);
    py::class_<LiquifyStroke>(module,"LiquifyStroke").def(py::init<>())
        .def_readwrite("tool",&LiquifyStroke::tool).def_readwrite("size",&LiquifyStroke::size)
        .def_readwrite("density",&LiquifyStroke::density).def_readwrite("pressure",&LiquifyStroke::pressure)
        .def_readwrite("rate",&LiquifyStroke::rate).def_readwrite("points",&LiquifyStroke::points)
        .def_readwrite("amount",&LiquifyStroke::amount);
    py::class_<LiquifyOptions>(module,"LiquifyOptions").def(py::init<>())
        .def_readwrite("cell",&LiquifyOptions::cell).def_readwrite("strokes",&LiquifyOptions::strokes);
    py::class_<VanishingPlane>(module,"VanishingPlane").def(py::init<>()).def_readwrite("corners",&VanishingPlane::corners);
    py::enum_<VanishingEdge>(module,"VanishingEdge").value("TOP",VanishingEdge::Top)
        .value("RIGHT",VanishingEdge::Right).value("BOTTOM",VanishingEdge::Bottom).value("LEFT",VanishingEdge::Left);
    py::class_<VanishingTearOff>(module,"VanishingTearOff").def(py::init<>())
        .def_readwrite("from_plane",&VanishingTearOff::from).def_readwrite("edge",&VanishingTearOff::edge)
        .def_readwrite("angle",&VanishingTearOff::angle).def_readwrite("depth",&VanishingTearOff::depth);
    py::class_<VanishingCloneStroke>(module,"VanishingCloneStroke").def(py::init<>())
        .def_readwrite("source",&VanishingCloneStroke::source).def_readwrite("points",&VanishingCloneStroke::points)
        .def_readwrite("size",&VanishingCloneStroke::size).def_readwrite("hardness",&VanishingCloneStroke::hardness)
        .def_readwrite("opacity",&VanishingCloneStroke::opacity);
    py::class_<OwnedVanishingPaste>(module,"VanishingPaste").def(py::init<>())
        .def_readwrite("image",&OwnedVanishingPaste::image).def_readwrite("plane",&OwnedVanishingPaste::plane)
        .def_readwrite("at",&OwnedVanishingPaste::at).def_readwrite("width",&OwnedVanishingPaste::width)
        .def_readwrite("opacity",&OwnedVanishingPaste::opacity);
    py::class_<VanishingPointParameters>(module,"VanishingPointParameters").def(py::init<>())
        .def_readwrite("planes",&VanishingPointParameters::planes).def_readwrite("tear_offs",&VanishingPointParameters::tearOffs)
        .def_readwrite("focal_length",&VanishingPointParameters::focalLength)
        .def_readwrite("pastes",&VanishingPointParameters::pastes).def_readwrite("clones",&VanishingPointParameters::clones);
}
} // namespace iiGraphicAdjust::python
