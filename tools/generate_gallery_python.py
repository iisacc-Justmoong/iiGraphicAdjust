#!/usr/bin/env python3
"""Regenerate Python value bindings for all declared GalleryEffect settings.

Only declarations in the public GalleryFilters header are consumed.  Generated
files are checked in so consuming this SDK never requires a code generator.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "src/Filters/GalleryFilters.h").read_text(encoding="utf-8")
records = re.findall(r"^struct (Gallery\w+Options) final\s*\{(.*?)^};", source, re.M | re.S)
variant = re.search(r"using GalleryEffect\s*=\s*std::variant<(.*?)>;", source, re.S)
if variant is None:
    raise SystemExit("GalleryEffect variant was not found")
names = re.findall(r"Gallery\w+Options", variant.group(1))
if [name for name, _ in records] != names:
    raise SystemExit("GalleryEffect and gallery settings declarations differ")

def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()

enums = re.findall(r"enum class (Gallery\w+)\s*\{(.*?)\};", source, re.S)
files = {key: ['#include "AdvancedPython.h"', '',
               'namespace iiGraphicAdjust::python {',
               '// Generated by tools/generate_gallery_python.py from the public settings contract.',
               f'void bindGallery{key}(py::module_& module) {{'] for key in "ABC"}
for name, body in enums:
    values = [value.strip() for value in body.split(",") if value.strip()]
    files["A"].append(f'    py::enum_<{name}>(module,"{name}")')
    files["A"].extend(f'        .value("{snake(value).upper()}",{name}::{value})' for value in values)
    files["A"][-1] += ";"

for index, (name, body) in enumerate(records):
    key = "A" if index < 16 else "B" if index < 32 else "C"
    fields = re.findall(r"^\s*(?:double|bool|std::uint32_t|Gallery\w+)\s+(\w+)\s*=", body, re.M)
    if not fields:
        raise SystemExit(f"No fields found for {name}")
    files[key].append(f'    py::class_<{name}>(module,"{name}").def(py::init<>())')
    files[key].extend(f'        .def_readwrite("{snake(field)}",&{name}::{field})' for field in fields)
    files[key][-1] += ";"

for key, lines in files.items():
    lines += ["}", "} // namespace iiGraphicAdjust::python", ""]
    target = ROOT / f"src/Python/Gallery{key}Python.cpp"
    content = "\n".join(lines)
    if "--check" in sys.argv:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Stale generated bindings: {target}")
    else:
        target.write_text(content, encoding="utf-8")
